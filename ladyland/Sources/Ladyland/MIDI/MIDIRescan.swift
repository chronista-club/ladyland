//! 起動直後の CoreMIDI 列挙レースを救う再列挙ポリシー。
//!
//! ## なぜ要るか（実測 2026-08-09 01:58）
//!
//! **実機（Keystage / ROTO）が繋がっているのに、起動時の列挙が空を返した** —
//! アプリは「実機なし（挿されたら再接続）」と印字したが、CoreMIDI から見れば
//! **その後何も変わらない**ので `msgSetupChanged` は来ない = **永遠に盲目**。
//! アプリを再起動したら普通に見えた。
//!
//! ⭐ **通知経路そのものは生きている**と実証済み（同 02:59、仮想ソースを
//! 立てた瞬間に両サービスが再接続した）。だからここで救うのは
//! **「変化が無いのに見えていない」起動レースだけ** — 見つかるまで
//! 数回だけ引き直し、それでも居なければ通知に任せて黙る。
//!
//! ## ⚠️ 再試行は `connect()` を直接呼ぶこと
//!
//! `reconnect()` は**予算をリセットする**（挿抜通知 = 新しい合図なので
//! 引き直す権利が戻る）。再試行側が `reconnect()` を呼ぶと、失敗のたびに
//! 予算が戻って**無限ループ**になる。

import Foundation

enum MIDIRescan {
    /// 再列挙までの待ち（秒）。**有限**であることが本体 — 実機が本当に
    /// 居ないとき（スタジオ外での起動など）は 3 回で黙り、以後は
    /// `msgSetupChanged`（挿されたときに来る）に任せる
    static let delays: [Double] = [2, 5, 10]

    /// attempt 回目（0 始まり）の失敗の後、何秒後に引き直すか。nil = 打ち止め
    static func delay(afterAttempt attempt: Int) -> Double? {
        guard attempt >= 0, attempt < delays.count else { return nil }
        return delays[attempt]
    }
}
