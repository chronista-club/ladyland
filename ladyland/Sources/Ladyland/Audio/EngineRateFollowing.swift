//! **エンジンの出力レートに追従する楽器**（mako 指示 2026-08-07
//! 「LadySynth もシステムの sample に連動するようにしよう」）。
//!
//! ## なぜ protocol にするか
//!
//! ⚠️ **このバグの正体は「具体型で絞ったので、新しい楽器を足したときに黙って
//! 漏れた」こと。** `InstrumentRack` の追従は `as? LadySampler` で絞っていたので、
//! `LadySynth` にレートが渡らず、実機で:
//!
//! ```
//! render: sampler 192000Hz（実測一致）
//! render: synth    44100Hz（実測一致）   ← 4.35 倍ずれる
//! ```
//!
//! **同じ形の漏れが 4 箇所**あった（追従本体 / ロード時のバス形式 /
//! ロード直後の取り直し / 形式の突き合わせログ）。1 つ直しても他が残る。
//!
//! protocol にすれば **次に楽器を足す人は適合を強制される** —
//! 実行時に「揃っていないぞ」と検知する仕掛けは要らなくなる。
//! **検知器が要るのは「起きうるから」で、型で起きなくしたなら不要**。
//!
//! ## ⚠️ レートから導く値は「持たない」のが正しい
//!
//! `LadySynth` を洗ったところ、レートから導く値は**すべて render のたびに
//! 計算し直していた**（キャッシュを持っていない）:
//!
//! | 値 | 式 | レートが変わったら |
//! |---|---|---|
//! | `inverseRate` | `1 / sampleRate` | 毎 render 再計算 ✅ |
//! | `follow`（エンベロープ追従） | `min(1, 200 * inverseRate)` | 毎 render 再計算 ✅ |
//! | `increment`（位相増分） | `frequency * inverseRate` | 毎 voice 毎 render ✅ |
//! | `voice.phase` | **0...1 に正規化** | そもそもレートに依存しない ✅ |
//! | `voice.envelope` | 0...1 | 同上 ✅ |
//!
//! ⚠️ `follow = 200 / rate` は**時定数を秒で一定に保つ**式になっている
//! （44.1k で τ≈220 サンプル = 5.0ms、192k で τ≈960 サンプル = 5.0ms）。
//! **サンプル数で持っていたら 192k で 4.35 倍速いエンベロープになっていた**。
//!
//! つまり `LadySynth` は**元からレートに対して正しく書かれていて、
//! 新しいレートを教えられていなかっただけ**。だから `refreshEngineRate()` は
//! `sampleRate` を読み直すだけで足りる。
//!
//! ⚠️ `LadySampler` は事情が違う — **メモリ上のバッファがレートに紐づく**ので、
//! 読み直しに加えて**全部の変換をやり直す**。だから「何をすべきか」は
//! 楽器ごとに違い、protocol は**呼ばれること**だけを保証する。

import AudioToolbox

/// **出力レートの変化に追従できる楽器**。
///
/// ⚠️ `AUAudioUnit` に制約してあるので、適合させる側は `outputBusses` を
/// 持っていることが保証される（追従側が形式を読むために要る）。
///
/// ⚠️ **`refreshEngineRate()` は引数を取らない** — 渡されたレートではなく
/// **自分の出力バスの形式**を読み直す。ここを引数にすると
/// 「デバイスのレートを渡す」という間違いができてしまい、実際に踏んだ
/// （バスが 44.1k のままなのに 192k と教えられ、4.35 倍速になった）
protocol EngineRateFollowing: AUAudioUnit {
    /// **繋ぎ替えの前に、鳴っているものを止める**。
    ///
    /// ⚠️ **鳴らしたまま繋ぎ替えると古いレートの音が一瞬漏れる**。
    /// さらにレートが変われば位相増分も変わるので、**続けると音程が途中で飛ぶ**。
    ///
    /// **切る側に倒す**（mako 判断の余地はあるが、こちらを選んだ）:
    /// デバイス切替は**演奏中には起きない**のに対し、音程が飛ぶのは
    /// 起きたら必ず聞こえる。起きない事故より、起きる事故を潰す。
    func silenceForRateChange()

    /// **出力バスの形式を読み直して、レートから導く値を作り直す**。
    ///
    /// ⚠️ 呼ぶのは**バスの形式を書き換えた後**。順序を逆にすると古い値を読む
    func refreshEngineRate()
}

extension LadySampler: EngineRateFollowing {
    /// パッドは**頭出し + 停止**（`stopAll` が All Notes Off と同じ扱いをする）
    func silenceForRateChange() { stopAll() }
}

extension LadySynth: EngineRateFollowing {}
