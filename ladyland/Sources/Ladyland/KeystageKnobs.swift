//! **Keystage のノブが送る CC**（mako 裁定 2026-08-07 夜
//! 「ノブ帯を base = 0 / pageCount = 8（CC0-63）へ」）。
//!
//! ⭐ **P1 = CC0-7 … P8 = CC56-63**（`base = 0` / 8 ページ / 64 席）。
//! ⭐ **ladyland の P1 = デバイスのページ 1** で番号がそのまま一致する。
//!
//! ⭐ **`0 + 8 × 8 == 64`** — 端数なく **Damper の壁（CC64）にぴたり収まる**。
//!
//! ## 機材の作り（実測 2026-08-07）
//!
//! 物理ノブが送る CC は「**デバイスがいま何ページ目か**」で決まり、
//! **PAGE -/+ がそれを動かす**:
//!
//!     デバイスのページ 1 = Knob-1..8 = CC0-7
//!     デバイスのページ 2 =           = CC8-15
//!     …
//!
//! ⚠️ **`KnobSelect`（KONTROL EDITOR の `Knob CC 0~7` / `8~15` …）は
//! 表示切替だった** — 「物理 8 ノブがどの組を送るかを選ぶ設定」と読んでいたが、
//! **実機ではページがそれを決めている**（mako 確認 2026-08-07 夜）。
//! ⭐ **だから mako 側の設定は要らない**。
//!
//! つまり **物理は 8 本のまま、送る番号だけが 8 ずつずれる**。
//! ladyland から見れば「**CC 番号がページを自己申告している**」。
//!
//! ## ⭐ だからページ状態を持たない
//!
//! ⚠️ **ページ送りのメッセージを受け取る必要が無い。** 回された CC 番号から
//! ページもページ内位置も引ける:
//!
//!     ページ     = (cc - base) / 8
//!     ページ内位置 = (cc - base) % 8
//!
//! ⭐ **これは「送ったものを真実として持つ」病から構造的に自由な部分**
//! （2026-08-07 に `RotoShadow` / `currentFace` / `motorRaw` で 3 度踏んだ）。
//! **真実は常に「最後に来た CC 番号」**なので、状態を持てば必ずズレる。
//! 表示のために覚えるとしても**キャッシュ**であって、真実ではない。
//!
//! ## ⭐ なぜ 8 ページにできたか — 演奏席を帯の外へ退かせたから
//!
//! **一度は 6 ページ（16-63）で打ち止めていた**。0-63 を取れなかった理由は
//! **帯の中に「楽器へ通さなければいけない席」が 2 つ居た**こと:
//!
//! | CC | 何 | どうしたか |
//! |---|---|---|
//! | **1** | Mod ホイール（ネイティブ） | **116 へ焼いた**（2026-08-05 に 119、08-07 に 116） |
//! | **11** | Expression | **115 へ焼いた**（2026-08-07。`FaceKnobAssignment.expressionCC`） |
//!
//! ⚠️ **どちらも物理ノブと同番号だったのが本質**。素通しが要る席とノブ席が
//! 同じ番号を送っていたので、**横取りすると演奏が死に、通すとノブが効かない**。
//! **番号ごと帯の外（111-116 の空き帯）へ退かせて、初めて 0-63 が空いた。**
//!
//! ## ⚠️ 下へ降りても帯から出ない — これが 0 始まりの本当の利点
//!
//! `base = 16` だと **ladyland の P1 がデバイスのページ 3** になる。
//! そこから **PAGE − で下へ降りると CC0-15 = 帯の外**なので、
//! **横取りされずに楽器へ素通しする** — ⚠️ **CC7 = Channel Volume で
//! 音量が飛び、CC0 = Bank Select が音色を狙う**。
//!
//! ⭐ `base = 0` なら **どこまで降りても帯の中**。下側の穴が塞がる。
//!
//! ## ⚠️⚠️ それでも 8 で打ち止め — 9 ページ目はペダル帯
//!
//! 上へは壁が残る。**P8 から PAGE + を押すと CC64-71 に着く**:
//!
//! ⚠️⚠️ **そのとき「ノブ 1 = CC64 = Sustain」になる。回すとサステインが
//! 入りっぱなしになる。** しかも**ペダルと区別が付かない**ので、横取りして
//! 塞ぐと**ペダルが死ぬ**。**この事故を避けるために `limit = 64` がある。**
//!
//! ⚠️ **次に見た人へ**: `pageCount` を 9 にすると `limit` との等式が破れて
//! `fillsExactlyUpToPedalRange` が落ちる。**その番人を消すな** —
//! 消して伸ばすと**ステージでサステインが固まる**。
//!
//! ## ボタンは移さない — 96-107 は空き席のまま
//!
//! 一度「焼いたボタンを 108-116 へ後ろ寄せ」という案が出たが、**あれは
//! 8 ページのために 96-107 を空ける目的**だった。⭐ **0-63 で 8 ページが
//! 取れたので理由が消えた**。⚠️ **`ladylandButtonCCs`（102-110）はそのまま** —
//! 不要な焼き直しは mako の割当をまた飛ばす。**96-107 は空き席として残る**。
//!
//! ## ⚠️ 番号を直書きしない
//!
//! `base` と `pageCount` から導く。**2026-08-07 だけで番号は 4 回動いている**
//! （0-7 → 24 → 16 → 0）。直書きした所は、動いた瞬間に黙って外れる。

import Foundation

enum KeystageKnobs {
    // ⭐ **実機との接続宣言: デバイスのページ n = `KnobPages` のページ n。**
    //
    // ページと席の定義そのものは `KnobPages`（正典）— 2026-08-10 に Keystage
    // から独立させた（mako 裁定「A だね。近いうち、2nd キーボードが増える」）。
    // ⚠️ **新しいサーフェスはこのファイルではなく `KnobPages` を参照する** —
    // ここに残るのは「Keystage という機材の事実」だけ。
    //
    // 帯が CC0 から始まる（= デバイスのページ 1 = CC0-7）ので、ladyland の
    // P1 とデバイスのページ 1 は番号がそのまま一致する。
    //
    // ⚠️ **CC0-15 には仕様で意味を持つ番号が並ぶ**: Bank Select(0) / Mod(1) /
    // Breath(2) / Foot(4) / Portamento Time(5) / Data Entry(6) /
    // **Channel Volume(7)** / Pan(10) / Expression(11)。だから全部飲む
    // （`intercepted`）— 番号の意味は**届かなければ無関係**になる。
    // 実測 2026-08-07: 素通ししていた頃は **CC7 で楽器の音量が直接動いた**。
    // ⚠️ Mod と Expression だけは素通しが要るので**番号ごと 116 / 115 へ
    // 退かせてある**（`FaceKnobAssignment.modWheelCC` / `.expressionCC`）

    /// ⭐ **楽器へ流さない集合**（帯 = `KnobPages.all` の全席）。
    ///
    /// ⚠️ **割当の有無に関わらず全部飲む**のが安全の本体。
    /// ⭐ とくに **CC32 が危ない**: VALUE エンコーダーが Program Change を
    /// 出しているので、**CC32 + PC でバンクが変わる**組み合わせが成立する。
    /// 横取りで消える。
    static let intercepted = Set(KnobPages.all)
}
